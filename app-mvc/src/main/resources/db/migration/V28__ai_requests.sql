-- AI 요청하기(ADR-005). 새 테이블 세 개만 더한다 — 기존 테이블은 건드리지 않는다.

CREATE TABLE ai_requests (
    id UUID PRIMARY KEY,
    member_id BIGINT NOT NULL,
    text TEXT,
    image_keys JSONB NOT NULL DEFAULT '[]'::jsonb,
    status VARCHAR(20) NOT NULL
        CHECK (status IN ('RECEIVED', 'PROCESSING', 'DRAFTED', 'APPLIED', 'FAILED', 'DEAD')),
    attempts INT NOT NULL DEFAULT 0,
    -- PROCESSING 의 리스 만료 시각. FAILED 에서는 "다음 재시도 가능 시각" 으로 재사용한다.
    lease_until TIMESTAMP(6),
    summary TEXT,
    last_error TEXT,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6)
);

-- 사용자당 진행 중 요청은 하나뿐이다(AI-AC-02). 서비스 검사를 우회한 동시 제출도 DB 가 막는다.
CREATE UNIQUE INDEX ai_requests_one_inflight
    ON ai_requests (member_id)
    WHERE status IN ('RECEIVED', 'PROCESSING', 'FAILED');

CREATE INDEX ai_requests_status_lease ON ai_requests (status, lease_until);

CREATE TABLE ai_outbox (
    event_id UUID PRIMARY KEY,
    request_id UUID NOT NULL REFERENCES ai_requests (id) ON DELETE CASCADE,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'PUBLISHED', 'DEAD')),
    attempts INT NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP(6) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL
);

CREATE INDEX ai_outbox_due ON ai_outbox (status, next_attempt_at);

CREATE TABLE ai_request_actions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id UUID NOT NULL REFERENCES ai_requests (id) ON DELETE CASCADE,
    action_key VARCHAR(100) NOT NULL,
    type VARCHAR(30) NOT NULL CHECK (type IN ('ROUND_PRODUCTS', 'TASK')),
    payload JSONB NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'APPLIED', 'REJECTED')),
    created_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT ai_request_actions_unique_key UNIQUE (request_id, action_key)
);
