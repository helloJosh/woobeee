package com.woobeee.mvc.pokemon.entity;

/** 차수의 환율을 어떻게 잡을지. 주최자가 차수를 열 때 고른다. */
public enum PokemonRateMode {
    /**
     * 차수가 들고 있는 환율 하나로 전부 계산한다. 마감 뒤 한 번에 결제하는 보통의 공동구매에
     * 맞고, "왜 나만 더 내요" 가 나오지 않는다. 주최자가 값을 직접 고칠 수 있지만, 고쳐도
     * 이미 들어온 신청서는 각자 박아 둔 환율을 유지한다.
     */
    FIXED,
    /** 신청서마다 그 시점 환율. 오래 열어 두어 환율이 크게 움직이는 차수에 맞다. */
    PER_ORDER
}
