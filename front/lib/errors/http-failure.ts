/**
 * HTTP 상태만으로 설명할 수 있는 실패의 문구.
 *
 * 여기 있는 것은 **응답 본문이 없어서** 오류 코드 지도(`error-messages.ts`)를 쓸 수 없는
 * 경우뿐이다. 413 이 그렇다 — 컨테이너가 multipart 를 파싱하다 상한을 넘겨 끊으므로
 * `ApiResponse` 봉투가 만들어지기 전에 응답이 나가고, 본문이 비어 있다. 그러면 호출부의
 * 일반 실패 문구로 뭉개져서 사용자는 크기 문제라는 것을 알 수 없다.
 *
 * 그 외 상태는 null 이다 — 여기서 문구를 만들면 코드 기반 지도를 가린다.
 */
export const describeHttpFailure = (status: number): string | null =>
    status === 413
        ? "파일이 너무 큽니다. 서버가 허용하는 크기를 넘었습니다 — 더 작은 이미지로 다시 시도해 주세요."
        : null
